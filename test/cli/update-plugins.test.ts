import { existsSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { UpdateCommand } from "../../src/cli/update.js";
import { packageVersion } from "../../src/core/paths.js";
import { pluginProject } from "../helpers/plugin-project.js";
import { runCommand } from "../helpers/run-command.js";

/** A CLI that is already current, so `update` goes straight to refreshing the project's files. */
class Current extends UpdateCommand {
  protected override async latestVersion(): Promise<string | null> {
    return packageVersion();
  }
}

describe("ambykit update refreshes plugin targets too (feature 027)", () => {
  it("027:FR-003: a listed plugin's target is regenerated by `update`", async () => {
    const root = pluginProject({ tools: ["fake"], plugins: { "ambykit-emitter-fake": "1.2.3" } });
    mkdirSync(join(root, "specs"), { recursive: true }); // projectAtCwd needs `.amby/` and `specs/`
    const r = await runCommand(new Current(), root, []);
    expect(r.code).toBe(0);
    expect(existsSync(join(root, ".fake", "commands", "amby.specify.md"))).toBe(true);
  });

  it("027:FR-004: a plugin that fails to load is reported by `update`, and built-in targets still refresh", async () => {
    const root = pluginProject({ tools: ["claude", "fake"], plugins: { "ambykit-emitter-fake": "1.2.3" }, install: [] });
    mkdirSync(join(root, "specs"), { recursive: true });
    const r = await runCommand(new Current(), root, []);
    expect(`${r.out}\n${r.err}`).toMatch(/Plugin ambykit-emitter-fake was not loaded/);
    expect(existsSync(join(root, ".claude", "commands", "amby.specify.md"))).toBe(true);
  });
});
