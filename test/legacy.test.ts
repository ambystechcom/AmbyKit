import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { legacyWorkflowFiles } from "../src/core/legacy.js";
import type { AmbyConfig } from "../src/core/types.js";

/** Stale generated Antigravity workflows (feature 018, FR-005/FR-006). */

const cfg = (tools: string[]): AmbyConfig => ({ version: "0.0.0", tools, manageRules: true });
const NOTICE = "<!-- GENERATED by AmbyKit from src/prompts/specify.md — do not edit by hand; run `ambykit sync`. -->";

function project(files: Record<string, string>): string {
  const root = mkdtempSync(join(tmpdir(), "ambykit-legacy-"));
  mkdirSync(join(root, ".agents", "workflows"), { recursive: true });
  for (const [name, body] of Object.entries(files)) writeFileSync(join(root, ".agents", "workflows", name), body);
  return root;
}

describe("legacyWorkflowFiles", () => {
  it("finds generated phase workflows", () => {
    const root = project({ "amby.specify.md": `---\n---\n${NOTICE}\n`, "amby.plan.md": `${NOTICE}\n` });
    expect(legacyWorkflowFiles(root, cfg(["antigravity"])).sort()).toEqual([
      ".agents/workflows/amby.plan.md",
      ".agents/workflows/amby.specify.md",
    ]);
    expect(legacyWorkflowFiles(root, cfg(["antigravity-cli"]))).toHaveLength(2);
  });

  it("ignores user workflows, .bak files and non-phase names", () => {
    const root = project({
      "amby.specify.md": "my own workflow\n", // phase name but not generated
      "amby.plan.md.bak": `${NOTICE}\n`, // left by Antigravity's migration
      "amby.custom.md": `${NOTICE}\n`, // not a phase
      "deploy.md": "x\n",
    });
    expect(legacyWorkflowFiles(root, cfg(["antigravity"]))).toEqual([]);
  });

  it("reports nothing without an Antigravity target", () => {
    const root = project({ "amby.specify.md": `${NOTICE}\n` });
    expect(legacyWorkflowFiles(root, cfg(["claude", "codex"]))).toEqual([]);
  });

  it("reports nothing when the workflows directory is absent", () => {
    const root = mkdtempSync(join(tmpdir(), "ambykit-legacy-"));
    expect(legacyWorkflowFiles(root, cfg(["antigravity"]))).toEqual([]);
  });
});
