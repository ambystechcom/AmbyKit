import { describe, expect, it } from "vitest";
import { loadCommandSpecs } from "../src/core/command-spec.js";
import { emitFiles, emitTarget } from "./helpers/emit-target.js";

/** Qwen, Kilo, Augment and Windsurf (feature 016, US-2, FR-005/009/011). */

const specs = loadCommandSpecs();

/** Keys of a leading `---` YAML block, in order ([] when there is none). */
function frontmatterKeys(text: string): string[] {
  const m = /^---\n([\s\S]*?)\n---\n/.exec(text);
  return m ? m[1]!.split("\n").map((l) => l.split(":")[0]!) : [];
}

const TARGETS = [
  { id: "qwen", dir: ".qwen/commands", keys: ["description", "argument-hint"], args: "{{args}}" },
  { id: "kilo", dir: ".kilo/commands", keys: ["description"], args: "$ARGUMENTS" },
  { id: "augment", dir: ".augment/commands", keys: ["description", "argument-hint"], args: "$ARGUMENTS" },
  { id: "windsurf", dir: ".windsurf/workflows", keys: [], args: "the user's request that followed this workflow invocation" },
] as const;

describe.each(TARGETS)("$id emitter", ({ id, dir, keys, args }) => {
  const files = emitTarget(id);

  it("emits exactly one file per phase plus the shared AGENTS.md, and no rules file of its own", () => {
    const expected = [...specs.map((s) => `${dir}/${s.name}.md`), "AGENTS.md"].sort();
    expect(Object.keys(files).sort()).toEqual(expected);
  });

  it("writes the documented frontmatter keys and nothing else", () => {
    for (const s of specs) expect(frontmatterKeys(files[`${dir}/${s.name}.md`]!), s.name).toEqual(keys);
  });

  it("handles the argument placeholder natively or by rewording", () => {
    const text = files[`${dir}/amby.specify.md`]!;
    expect(text).toContain(args);
    if (args !== "$ARGUMENTS") expect(text).not.toContain("$ARGUMENTS");
    expect(text).toContain(`--agent=${id}`);
  });

  it("keeps the generated notice and every file project-scoped", () => {
    for (const f of emitFiles([id])) expect(f.scope).toBe("project");
    expect(files[`${dir}/amby.plan.md`]).toContain("GENERATED by AmbyKit from src/prompts/plan.md");
  });
});

describe("Windsurf workflow size limit", () => {
  it("keeps every workflow at or under 12,000 characters", () => {
    const files = emitTarget("windsurf", { roles: true });
    for (const [path, text] of Object.entries(files)) {
      if (path.startsWith(".windsurf/workflows/")) expect(text.length, path).toBeLessThanOrEqual(12_000);
    }
  });
});
