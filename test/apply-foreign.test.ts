import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { applyFiles } from "../src/cli/io/fsops.js";
import type { EmittedFile } from "../src/core/types.js";

/** Foreign-file guard (feature 018, FR-016). */

const PATH = ".agents/skills/amby-specify/SKILL.md";
const file = (over: Partial<EmittedFile> = {}): EmittedFile => ({
  path: PATH,
  contents: "<!-- GENERATED by AmbyKit from src/prompts/specify.md -->\nnew\n",
  scope: "project",
  protectForeign: true,
  ...over,
});

function project(existing?: string): string {
  const root = mkdtempSync(join(tmpdir(), "ambykit-foreign-"));
  if (existing !== undefined) {
    mkdirSync(join(root, ".agents", "skills", "amby-specify"), { recursive: true });
    writeFileSync(join(root, PATH), existing);
  }
  return root;
}

describe("applyFiles protectForeign", () => {
  it("leaves a file without the generated notice alone and reports it", () => {
    const root = project("my own skill\n");
    const r = applyFiles(root, [file()], { dryRun: false, includeUser: false });
    expect(r.skippedForeign).toEqual([PATH]);
    expect(r.written).toEqual([]);
    expect(readFileSync(join(root, PATH), "utf8")).toBe("my own skill\n");
  });

  it("overwrites a previously generated file", () => {
    const root = project("<!-- GENERATED by AmbyKit from src/prompts/specify.md -->\nold\n");
    const r = applyFiles(root, [file()], { dryRun: false, includeUser: false });
    expect(r.updated).toEqual([PATH]);
    expect(r.skippedForeign).toEqual([]);
  });

  it("creates the file when nothing exists", () => {
    const r = applyFiles(project(), [file()], { dryRun: false, includeUser: false });
    expect(r.created).toEqual([PATH]);
  });

  it("reports a foreign file in a dry run without listing it as a change", () => {
    const r = applyFiles(project("mine\n"), [file()], { dryRun: true, includeUser: false });
    expect(r.skippedForeign).toEqual([PATH]);
    expect(r.wouldChange).toEqual([]);
  });

  it("does not protect files that did not ask for it", () => {
    const root = project("mine\n");
    const r = applyFiles(root, [file({ protectForeign: false })], { dryRun: false, includeUser: false });
    expect(r.updated).toEqual([PATH]);
  });
});
