import { readdirSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { loadCommandSpecs } from "../src/core/command-spec.js";
import type { CommandSpec, RulesContext } from "../src/core/types.js";
import { GeminiEmitter, LlxprtEmitter } from "../src/emitters/index.js";
import { tomlBasic, tomlPrompt } from "../src/emitters/toml-command-emitter.js";
import { emitTarget } from "./helpers/emit-target.js";
import { parseMiniToml } from "./helpers/mini-toml.js";

/** Gemini CLI and LLxprt Code (feature 016, US-3, FR-004/009/011). */

const specs = loadCommandSpecs();
const ctx = (manageRules = true): RulesContext => ({ projectName: "demo", specs, manageRules });
const spec = (over: Partial<CommandSpec> = {}): CommandSpec => ({ ...specs.find((s) => s.id === "specify")!, ...over });
const PROMPTS = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "prompts");

const TARGETS = [
  { id: "gemini", dir: ".gemini/commands", rules: "GEMINI.md", Emitter: GeminiEmitter },
  { id: "llxprt", dir: ".llxprt/commands", rules: "LLXPRT.md", Emitter: LlxprtEmitter },
] as const;

describe.each(TARGETS)("$id emitter", ({ id, dir, rules, Emitter }) => {
  const files = emitTarget(id);

  it("emits exactly one TOML per phase plus the pointer file, and AGENTS.md", () => {
    const expected = [...specs.map((s) => `${dir}/${s.name}.toml`), rules, "AGENTS.md"].sort();
    expect(Object.keys(files).sort()).toEqual(expected);
  });

  it("writes `description` and `prompt` and nothing else, with a # notice", () => {
    for (const s of specs) {
      const text = files[`${dir}/${s.name}.toml`]!;
      expect(text.startsWith("# GENERATED by AmbyKit")).toBe(true);
      expect(Object.keys(parseMiniToml(text))).toEqual(["description", "prompt"]);
    }
  });

  it("round-trips every phase: description and prompt parse back to the neutral text", () => {
    for (const s of specs) {
      const parsed = parseMiniToml(files[`${dir}/${s.name}.toml`]!);
      expect(parsed["description"]).toBe(s.description);
      expect(parsed["prompt"]).toContain(s.body.split("\n")[0]!.replaceAll("$ARGUMENTS", "{{args}}"));
      expect(parsed["prompt"]).not.toContain("$ARGUMENTS");
    }
  });

  it("uses {{args}} for the argument placeholder and the tool id for self-report", () => {
    const text = parseMiniToml(files[`${dir}/amby.specify.toml`]!)["prompt"]!;
    expect(text).toContain("{{args}}");
    expect(text).toContain(`--agent=${id}`);
  });

  it("emits a merge-region pointer file, and none without manageRules", () => {
    const pointer = new Emitter().emit(specs, ctx()).find((f) => f.path === rules)!;
    expect(pointer.merge).toBe("region");
    expect(pointer.contents).toContain("### AmbyKit usage");
    expect(new Emitter().emit(specs, ctx(false)).some((f) => f.path === rules)).toBe(false);
  });
});

describe("TOML escaping", () => {
  const emit = (over: Partial<CommandSpec>): string => {
    const f = new GeminiEmitter().emit([spec(over)], ctx(false))[0]!;
    return f.contents;
  };

  it("escapes backslashes, quotes and control characters in the description", () => {
    const text = emit({ description: 'a "quoted" \\ back\tslash\nline' });
    expect(text).toContain('description = "a \\"quoted\\" \\\\ back\\tslash\\nline"');
    expect(parseMiniToml(text)["description"]).toBe('a "quoted" \\ back\tslash\nline');
  });

  it("keeps backslashes and quotes in the body verbatim inside a literal block", () => {
    const body = 'run "x" \\n C:\\path ${HOME}';
    const text = emit({ body });
    expect(text).toContain(`prompt = '''\n${body}`);
    expect(parseMiniToml(text)["prompt"]).toContain(body);
  });

  it("falls back to a basic block, escaped, when the body contains ''' ", () => {
    const body = "has ''' inside \\ and \"quotes\" and \"\"\" triple";
    const text = emit({ body });
    expect(text).toContain('prompt = """\n');
    expect(parseMiniToml(text)["prompt"]).toBe(`${body}\n`);
  });

  it("tomlPrompt/tomlBasic round-trip arbitrary text", () => {
    for (const s of ["plain", "it's", "''' nope", 'say "hi"', "tab\there", "back\\slash", "ctl\u0001char"]) {
      expect(parseMiniToml(`k = ${tomlBasic(s)}`)["k"]).toBe(s);
      expect(parseMiniToml(`k = ${tomlPrompt(s)}`)["k"]).toBe(`${s}\n`);
    }
  });
});

describe("neutral prompts are safe for Gemini's injection syntax (R1)", () => {
  it("contain no !{ , @{ or ''' sequences", () => {
    for (const f of readdirSync(PROMPTS).filter((n) => n.endsWith(".md"))) {
      const text = readFileSync(join(PROMPTS, f), "utf8");
      expect(text, f).not.toContain("!{");
      expect(text, f).not.toContain("@{");
      expect(text, f).not.toContain("'''");
    }
  });
});
