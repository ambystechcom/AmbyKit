import { describe, expect, it } from "vitest";
import { loadCommandSpecs } from "../src/core/command-spec.js";
import { emitTarget } from "./helpers/emit-target.js";

/** Antigravity targets emit skills, not the retired workflows (feature 018, FR-001..003, FR-014). */
describe.each([
  ["antigravity", "antigravity"],
  ["antigravity-cli", "antigravity-cli"],
])("%s emits skills", (target, agentId) => {
  const out = emitTarget(target, { manageRules: false });
  const specs = loadCommandSpecs();

  it("writes one SKILL.md per phase and no workflow file", () => {
    const paths = Object.keys(out);
    expect(paths.sort()).toEqual(specs.map((s) => `.agents/skills/${s.name.replace(/\./g, "-")}/SKILL.md`).sort());
    expect(paths.some((p) => p.includes("workflows"))).toBe(false);
  });

  it("gives each skill name == directory, a description, and only those keys", () => {
    for (const spec of specs) {
      const name = spec.name.replace(/\./g, "-");
      const text = out[`.agents/skills/${name}/SKILL.md`]!;
      const head = /^---\n([\s\S]*?)\n---\n/.exec(text)![1]!;
      expect(name).toMatch(/^[a-z0-9-]+$/);
      expect(head.split("\n").map((l) => l.split(":")[0])).toEqual(["name", "description"]);
      expect(head).toContain(`name: ${name}`);
      expect(head).toMatch(/description: ".+"/);
      expect(text).toContain("GENERATED by AmbyKit");
    }
  });

  it("leaves no literal argument placeholder and reports its own id", () => {
    for (const text of Object.values(out)) {
      expect(text).not.toContain("$ARGUMENTS");
      expect(text).not.toContain("$AGENT");
    }
    expect(out[".agents/skills/amby-specify/SKILL.md"]).toContain(`--agent=${agentId}`);
  });

  it("is a pure function of the neutral prompts (re-emit is identical)", () => {
    expect(emitTarget(target, { manageRules: false })).toEqual(out);
  });
});
