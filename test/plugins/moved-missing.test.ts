import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { CheckCommand } from "../../src/cli/check.js";
import { SyncCommand } from "../../src/cli/sync.js";
import { MOVED_TARGETS } from "../../src/core/moved-targets.js";
import { pluginProject } from "../helpers/plugin-project.js";
import { runCommand } from "../helpers/run-command.js";

/**
 * Feature 036, US-1 (T021): a moved target with no plugin names the target, prints the exact install and config lines, the other
 * targets still sync, the exit is non-zero, and no file is changed or deleted (FR-004, FR-005, FR-006). The per-command cases
 * (sync, check, update) are in moved-failure.test.ts; this file adds the exact wording, the whole-tree guarantee and the cases
 * for several moved targets and for `--dry-run` / `--check`.
 */

const PACKAGE = "@ambystech/ambykit-emitter-gone";
const text = (r: { out: string; err: string }): string => `${r.out}\n${r.err}`;

/** Every file under `root` (relative path -> contents), skipping nothing: used before and after to prove nothing was touched. */
function snapshot(root: string): Record<string, string> {
  const out: Record<string, string> = {};
  const walk = (dir: string): void => {
    for (const name of readdirSync(dir)) {
      const abs = join(dir, name);
      if (statSync(abs).isDirectory()) walk(abs);
      else out[abs.slice(root.length + 1).replaceAll("\\", "/")] = readFileSync(abs, "utf8");
    }
  };
  walk(root);
  return out;
}

function project(tools: string[]): string {
  const root = pluginProject({ tools });
  mkdirSync(join(root, "specs"), { recursive: true });
  // Files an earlier release wrote for the moved targets, with a hand edit in one of them.
  for (const [rel, body] of [
    [".gone/commands/amby.specify.md", "written by an earlier release\n"],
    [".gone/commands/amby.plan.md", "<!-- GENERATED by AmbyKit -->\nand then edited by hand\n"],
  ] as const) {
    mkdirSync(dirname(join(root, rel)), { recursive: true });
    writeFileSync(join(root, rel), body);
  }
  return root;
}

describe("a moved target with no plugin installed (036:FR-004, FR-005, FR-006)", () => {
  afterEach(() => {
    delete MOVED_TARGETS["gone-a"];
    delete MOVED_TARGETS["gone-b"];
  });

  it("036:FR-004: the message names the target and the package, and prints the exact install line and the exact config line", async () => {
    MOVED_TARGETS["gone-a"] = { package: PACKAGE, since: "2.0.0" };
    const r = await runCommand(new SyncCommand(), project(["claude", "gone-a"]), []);
    const all = text(r);
    expect(all).toContain(`Target 'gone-a' moved to the plugin ${PACKAGE} (since 2.0.0).`);
    expect(all).toContain(`Run \`npm install --save-exact ${PACKAGE}\``);
    expect(all).toContain('list it under "plugins" in .amby/config.json with that exact version');
    expect(all).toContain("Files already written for it are left in place.");
  });

  it("036:FR-004: two moved targets are each named once, with their own package, and the other targets still sync (exit 1)", async () => {
    MOVED_TARGETS["gone-a"] = { package: PACKAGE, since: "2.0.0" };
    MOVED_TARGETS["gone-b"] = { package: "@ambystech/ambykit-emitter-other", since: "2.0.0" };
    const root = project(["claude", "gone-a", "codex", "gone-b"]);
    const r = await runCommand(new SyncCommand(), root, []);
    expect(r.code).toBe(1);
    expect(text(r).match(/Target 'gone-a' moved to the plugin/g)).toHaveLength(1);
    expect(text(r).match(/Target 'gone-b' moved to the plugin/g)).toHaveLength(1);
    expect(text(r)).toContain("@ambystech/ambykit-emitter-other");
    expect(existsSync(join(root, ".claude", "commands", "amby.specify.md"))).toBe(true);
    expect(existsSync(join(root, ".agents", "skills", "amby-specify", "SKILL.md"))).toBe(true);
  });

  it("036:FR-005: no file that existed before is changed or deleted, and the only new files belong to the other targets", async () => {
    MOVED_TARGETS["gone-a"] = { package: PACKAGE, since: "2.0.0" };
    const root = project(["claude", "gone-a"]);
    const before = snapshot(root);
    await runCommand(new SyncCommand(), root, []);
    const after = snapshot(root);
    for (const [path, contents] of Object.entries(before)) {
      expect(after[path], `${path} must survive unchanged`).toBe(contents);
    }
    const added = Object.keys(after).filter((p) => !(p in before));
    expect(added.length).toBeGreaterThan(0);
    for (const p of added) expect(p.startsWith(".gone/"), `${p} must not be a moved target's file`).toBe(false);
  });

  it("036:FR-006: nothing is installed and no package file appears: the notice only says what to run", async () => {
    MOVED_TARGETS["gone-a"] = { package: PACKAGE, since: "2.0.0" };
    const root = project(["claude", "gone-a"]);
    await runCommand(new SyncCommand(), root, []);
    expect(existsSync(join(root, "node_modules"))).toBe(false);
    expect(existsSync(join(root, "package.json"))).toBe(false);
    expect(existsSync(join(root, "package-lock.json"))).toBe(false);
  });

  it("036:FR-004: --dry-run still reports the moved target, exits 1 and writes nothing", async () => {
    MOVED_TARGETS["gone-a"] = { package: PACKAGE, since: "2.0.0" };
    const root = project(["claude", "gone-a"]);
    const before = snapshot(root);
    const r = await runCommand(new SyncCommand(), root, [], { "dry-run": true });
    expect(r.code).toBe(1);
    expect(text(r)).toMatch(/Target 'gone-a' moved to the plugin/);
    expect(snapshot(root)).toEqual(before);
  });

  it("036:FR-004: sync --check reports the moved target and exits non-zero even when the other targets are in sync", async () => {
    MOVED_TARGETS["gone-a"] = { package: PACKAGE, since: "2.0.0" };
    const root = project(["claude", "gone-a"]);
    await runCommand(new SyncCommand(), root, []);
    const r = await runCommand(new SyncCommand(), root, [], { check: true });
    expect(r.code).toBe(1);
    expect(text(r)).toMatch(/Target 'gone-a' moved to the plugin/);
    expect(text(r)).not.toMatch(/Out of sync/);
  });

  it("036:FR-004: check says it once and does not also call the moved target unknown", async () => {
    MOVED_TARGETS["gone-a"] = { package: PACKAGE, since: "2.0.0" };
    const r = await runCommand(new CheckCommand(), project(["claude", "gone-a"]), []);
    expect(r.code).toBe(1);
    expect(text(r).match(/gone-a/g)!.length).toBeGreaterThan(0);
    expect(text(r)).not.toMatch(/'gone-a' is not a known target/);
    expect(text(r).match(/moved to the plugin/g)).toHaveLength(1);
  });
});
