import { existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { CheckCommand } from "../src/cli/check.js";
import { RestoreCommand } from "../src/cli/restore.js";
import { SyncCommand } from "../src/cli/sync.js";
import { runCommand } from "./helpers/run-command.js";

/** Migration from the workflows of earlier releases (feature 018, US-2, SC-002). */

const NOTICE = "<!-- GENERATED by AmbyKit from src/prompts/specify.md — do not edit by hand; run `ambykit sync`. -->";
const WF = ".agents/workflows";

function oldProject(tools = ["antigravity"]): string {
  const root = mkdtempSync(join(tmpdir(), "ambykit-mig-"));
  mkdirSync(join(root, ".amby"), { recursive: true });
  writeFileSync(join(root, ".amby", "config.json"), JSON.stringify({ version: "0.0.0", tools, manageRules: false }));
  mkdirSync(join(root, WF), { recursive: true });
  writeFileSync(join(root, WF, "amby.specify.md"), `---\ndescription: "x"\n---\n${NOTICE}\n\nbody\n`);
  writeFileSync(join(root, WF, "amby.plan.md"), `---\ndescription: "x"\n---\n${NOTICE}\n\nbody\n`);
  writeFileSync(join(root, WF, "deploy.md"), "my own workflow\n");
  return root;
}

describe("sync with stale Antigravity workflows", () => {
  it("writes the skills, keeps the old files and says how to remove them", async () => {
    const root = oldProject();
    const r = await runCommand(new SyncCommand(), root, []);
    expect(r.code).toBe(0);
    expect(existsSync(join(root, ".agents/skills/amby-specify/SKILL.md"))).toBe(true);
    expect(existsSync(join(root, WF, "amby.specify.md"))).toBe(true);
    expect(r.out + r.err).toContain("--prune-legacy");
    expect(r.out + r.err).toContain(`${WF}/amby.specify.md`);
  });

  it("removes only generated files with --prune-legacy, backing each up", async () => {
    const root = oldProject();
    const r = await runCommand(new SyncCommand(), root, [], { "prune-legacy": true });
    expect(r.code).toBe(0);
    expect(existsSync(join(root, WF, "amby.specify.md"))).toBe(false);
    expect(existsSync(join(root, WF, "amby.plan.md"))).toBe(false);
    expect(readFileSync(join(root, WF, "deploy.md"), "utf8")).toBe("my own workflow\n"); // user's own, untouched
    expect(existsSync(join(root, ".agents/skills/amby-plan/SKILL.md"))).toBe(true);
    const again = await runCommand(new SyncCommand(), root, []);
    expect(again.out + again.err).not.toContain("stale");
  });

  it("can bring a removed file back with restore", async () => {
    const root = oldProject();
    await runCommand(new SyncCommand(), root, [], { "prune-legacy": true });
    const r = await runCommand(new RestoreCommand(), root, [`${WF}/amby.specify.md`]);
    expect(r.code).toBe(0);
    expect(existsSync(join(root, WF, "amby.specify.md"))).toBe(true);
  });

  it("does nothing under --dry-run", async () => {
    const root = oldProject();
    await runCommand(new SyncCommand(), root, [], { "prune-legacy": true, "dry-run": true });
    expect(existsSync(join(root, WF, "amby.specify.md"))).toBe(true);
    expect(existsSync(join(root, ".agents/skills"))).toBe(false);
  });

  it("prints no stale message for a project without the old files or without Antigravity", async () => {
    const fresh = oldProject(["claude"]);
    const r = await runCommand(new SyncCommand(), fresh, []);
    expect(r.out + r.err).not.toContain("stale");
  });

  it("check lists the stale files without counting them as drift", async () => {
    const root = oldProject();
    await runCommand(new SyncCommand(), root, []);
    const r = await runCommand(new CheckCommand(), root, []);
    expect(r.out + r.err).toContain("stale Antigravity workflow");
    expect(r.out + r.err).not.toContain("out of sync");
  });

  it("leaves a user's skill with an AmbyKit name alone and check flags it", async () => {
    const root = oldProject(["codex"]);
    mkdirSync(join(root, ".agents/skills/amby-specify"), { recursive: true });
    writeFileSync(join(root, ".agents/skills/amby-specify/SKILL.md"), "mine\n");
    const s = await runCommand(new SyncCommand(), root, []);
    expect(readFileSync(join(root, ".agents/skills/amby-specify/SKILL.md"), "utf8")).toBe("mine\n");
    expect(s.out + s.err).toContain("did not generate");
    const c = await runCommand(new CheckCommand(), root, []);
    expect(c.code).toBe(1);
  });
});
