import { existsSync, readFileSync } from "node:fs";
import { join as nativeJoin } from "node:path";
import { join } from "node:path/posix";
import type { AmbyConfig } from "./types.js";
import { loadCommandSpecs } from "./command-spec.js";
import { getTarget } from "../emitters/index.js";

/** Where the Antigravity targets wrote phase commands before feature 018 (workflows, retired 2026-10-19). */
export const LEGACY_WORKFLOW_DIR = join(".agents", "workflows");

const GENERATED = "GENERATED by AmbyKit";

/**
 * Stale, AmbyKit-generated Antigravity workflow files (feature 018, FR-005/FR-006): project-relative
 * paths of `.agents/workflows/amby.<phase>.md` that exist **and** carry the generated notice. Empty
 * unless an Antigravity target is selected, so other projects never see a message. A user's own
 * workflow, a `.bak` left by Antigravity's migration, or a file with a non-phase name never matches.
 */
export function legacyWorkflowFiles(root: string, config: AmbyConfig): string[] {
  const antigravity = config.tools.some((id) => getTarget(id)?.emitter.toolId === "antigravity" || getTarget(id)?.emitter.toolId === "antigravity-cli");
  if (!antigravity) return [];
  const out: string[] = [];
  for (const spec of loadCommandSpecs()) {
    const rel = join(LEGACY_WORKFLOW_DIR, `${spec.name}.md`);
    const abs = nativeJoin(root, rel);
    if (!existsSync(abs)) continue;
    try {
      if (readFileSync(abs, "utf8").includes(GENERATED)) out.push(rel);
    } catch {
      // unreadable: leave it alone
    }
  }
  return out;
}
