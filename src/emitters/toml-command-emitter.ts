import type { CommandSpec, CommandSurface } from "../core/types.js";
import { BaseEmitter } from "./base-emitter.js";

/**
 * Base for tools whose custom commands are TOML files (Gemini CLI, LLxprt Code; feature 016, R1):
 *
 *     # <generated notice>
 *     description = "<basic-escaped>"
 *     prompt = '''
 *     <body>
 *     '''
 *
 * The prompt is a TOML *literal* multi-line string, so backslashes and quotes in the neutral body
 * need no escaping. A body containing `'''` falls back to a basic `"""` string with `\` and `"`
 * escaped. The generated notice is a `#` comment, so it costs no prompt tokens. `$ARGUMENTS` becomes
 * `{{args}}`. Only two string keys are written and AmbyKit never parses TOML, hence no dependency.
 */
export abstract class TomlCommandEmitter extends BaseEmitter {
  readonly commandSurface: CommandSurface = "commands";

  /** Commands live in `<dir>/amby.<phase>.toml`; dots are kept (the command name is the file path). */
  protected override commandFileName(spec: CommandSpec): string {
    return `${spec.name}.toml`;
  }

  protected override commandFrontmatter(spec: CommandSpec): Array<[string, string]> {
    return [["description", tomlBasic(spec.description)]];
  }

  protected override generatedNotice(spec: CommandSpec): string {
    return `# GENERATED by AmbyKit from src/prompts/${spec.id}.md — do not edit by hand; run \`ambykit sync\`.`;
  }

  protected override transformBody(spec: CommandSpec): string {
    return spec.body.replaceAll("$ARGUMENTS", "{{args}}");
  }

  protected override renderCommand(pairs: Array<[string, string]>, notice: string, body: string): string {
    const keys = pairs.map(([k, v]) => `${k} = ${v}`).join("\n");
    return `${notice}\n${keys}\nprompt = ${tomlPrompt(body)}\n`;
  }
}

/** TOML basic string (`"…"`) with the required escapes. */
export function tomlBasic(value: string): string {
  return `"${escapeBasic(value)}"`;
}

function escapeBasic(value: string): string {
  let out = "";
  for (const ch of value) {
    const code = ch.codePointAt(0)!;
    if (ch === "\\") out += "\\\\";
    else if (ch === '"') out += '\\"';
    else if (ch === "\n") out += "\\n";
    else if (ch === "\t") out += "\\t";
    else if (ch === "\r") out += "\\r";
    else if (code < 0x20 || code === 0x7f) out += `\\u${code.toString(16).toUpperCase().padStart(4, "0")}`;
    else out += ch;
  }
  return out;
}

/** The `prompt` value: a literal `'''` block, or a basic `"""` block when the body contains `'''`. */
export function tomlPrompt(body: string): string {
  if (!body.includes("'''") && !/[\u0000-\u0008\u000b-\u001f\u007f]/.test(body)) return `'''\n${body}\n'''`;
  // Multi-line basic string: keep real newlines (a leading one is trimmed by TOML), escape the rest.
  const escaped = body.split("\n").map(escapeBasic).join("\n");
  return `"""\n${escaped}\n"""`;
}
