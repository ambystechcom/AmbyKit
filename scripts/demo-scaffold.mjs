export function scaffold() {
  for (const [name, contents] of Object.entries(FILES)) {
    const path = join(demoDir, name);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, contents);
  }
  return Object.keys(FILES).length;
}

// Only act when run directly, so demo-reset.mjs can import scaffold() without side effects.
if (process.argv[1]?.endsWith("demo-scaffold.mjs")) {
  console.log(`Scaffolded ${scaffold()} file(s) into .demo/`);
}
