  "src/store.mjs": `// Tasks live in localStorage. No backend — this is a demo fixture, not a product.

const KEY = "taskflow.tasks";

export const COLUMNS = [
  { id: "todo", label: "To do" },
  { id: "doing", label: "In progress" },
  { id: "done", label: "Done" },
];

const SEED = [
  { id: 1, title: "Sketch the board layout", column: "done" },
  { id: 2, title: "Persist tasks across reloads", column: "doing" },
  { id: 3, title: "Drag a card between columns", column: "todo" },
];

export function load() {
  try {
    const raw = localStorage.getItem(KEY);
    return raw ? JSON.parse(raw) : structuredClone(SEED);
  } catch {
    // Private windows and cleared site data both land here. Seed rather than break.
    return structuredClone(SEED);
  }
}

export function save(tasks) {
  try {
    localStorage.setItem(KEY, JSON.stringify(tasks));
  } catch {
    // Nothing to do — the board still works for this session.
  }
}

export function add(tasks, title) {
  const id = tasks.reduce((max, t) => Math.max(max, t.id), 0) + 1;
  return [...tasks, { id, title, column: "todo" }];
}

export function moveTo(tasks, id, column) {
  return tasks.map((t) => (t.id === id ? { ...t, column } : t));
}
`,

  "src/app.js": `import { COLUMNS, add, load, moveTo, save } from "./store.mjs";

let tasks = load();

const board = document.getElementById("board");
const form = document.getElementById("new-task");
const input = document.getElementById("new-task-title");

function render() {
  board.replaceChildren(
    ...COLUMNS.map((col) => {
      const section = document.createElement("section");
      section.className = "column";

      const heading = document.createElement("h2");
      const inColumn = tasks.filter((t) => t.column === col.id);
      heading.textContent = \`\${col.label} (\${inColumn.length})\`;
      section.append(heading);

      for (const task of inColumn) {
        section.append(card(task));
      }
      return section;
    }),
  );
}

function card(task) {
  const el = document.createElement("article");
  el.className = "card";

  const title = document.createElement("p");
  title.textContent = task.title;
  el.append(title);

  const moves = document.createElement("div");
  moves.className = "moves";
  for (const col of COLUMNS) {
    if (col.id === task.column) continue;
    const button = document.createElement("button");
    button.textContent = col.label;
    button.addEventListener("click", () => {
      tasks = moveTo(tasks, task.id, col.id);
      save(tasks);
      render();
    });
    moves.append(button);
  }
  el.append(moves);

  return el;
}

form.addEventListener("submit", (event) => {
  event.preventDefault();
  const title = input.value.trim();
  if (!title) return;
  tasks = add(tasks, title);
  save(tasks);
  input.value = "";
  render();
});

render();
`,

